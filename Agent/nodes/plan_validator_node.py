"""

This node performs deterministic structural checks
on plans generated by the Planner Node. -> Important: It performs only structural checks, not if the plan is correct from a business perspective !!

It does not use an LLM, execute tools, or access ERPNext.
"""

from datetime import datetime, timezone

from Agent.state import PlanningState


def plan_validator(state: PlanningState) -> dict:
    """
    Validates a generated execution plan against the
    available tool catalog and structural requirements.

    Returns validation results as LangGraph state updates.
    """

    plan = state.get("plan", [])
    available_tools = state.get("available_tools", [])
    missing_info = state.get("missing_info", [])
    abort_reason = state.get("abort_reason", "")
    status = state.get("status")

    errors = []

    def create_log(result_status: str, errors: list[str]) -> dict:
        """
        Creates an auditable plan validation event.
        """

        return {
            "event": "plan_validated",
            "result": result_status,
            "valid": result_status == "plan_valid",
            "errors": errors.copy(),
            "step_count": len(plan) if isinstance(plan, list) else 0,
            "timestamp": datetime.now(
                timezone.utc
            ).isoformat()
        }

    def reject(errors: list[str]) -> dict:
        """
        Return a failed validation result.
        """

        return {
            "plan_valid": False,
            "validation_errors": errors,
            "status": "plan_invalid",
            "history": [
                create_log("plan_invalid", errors)
            ]
        }

    # Only validate plans that completed the planning stage.
    if status != "planned":
        return {
            "plan_valid": False,
            "validation_errors": [],
            "status": status or "planning_failed",
            "history": [{
                "event": "plan_validation_skipped",
                "reason": "Planning has not completed successfully.",
                "planning_status": status,
                "timestamp": datetime.now(
                    timezone.utc
                ).isoformat()
            }]
        }

    # Check whether planning reported unresolved information.
    if missing_info:
        errors.append(
            "The plan contains unresolved required information."
        )

    if abort_reason:
        errors.append(
            f"Planning reported an abort reason: {abort_reason}"
        )

    # Validate plan structure.
    if not isinstance(plan, list) or not plan:
        errors.append(
            "The execution plan must contain at least one step."
        )

   
    if not isinstance(available_tools, list):
        errors.append(
            "The available tool catalog must be a list."
        )
        available_tools = []

    # Extract and validate registered tool names.
    tool_names = set()

    for index, tool in enumerate(available_tools):
        if not isinstance(tool, dict):
            errors.append(
                f"Tool definition at index {index} is invalid."
            )
            continue

        name = tool.get("name")

        if not isinstance(name, str) or not name.strip():
            errors.append(
                f"Tool definition at index {index} has no valid name."
            )
            continue

        if name in tool_names:
            errors.append(
                f"Duplicate tool name in catalog: '{name}'."
            )

        tool_names.add(name)

    # Stop structural checks if the plan is not a list.
    if not isinstance(plan, list):
        return reject(errors)

    # Collect step IDs to validate dependencies.
    step_positions = {}

    for index, step in enumerate(plan):
        if not isinstance(step, dict):
            errors.append(
                f"Step at index {index} must be an object."
            )
            continue

        step_id = step.get("id")

        if not isinstance(step_id, str) or not step_id.strip():
            errors.append(
                f"Step at index {index} has no valid ID."
            )
            continue

        if step_id in step_positions:
            errors.append(
                f"Duplicate step ID: '{step_id}'."
            )
        else:
            step_positions[step_id] = index

    # Validate each step independently.
    for index, step in enumerate(plan):
        if not isinstance(step, dict):
            continue

        step_id = step.get("id")
        step_label = step_id or f"index {index}"

        # Validate the selected tool.
        tool_name = step.get("tool")

        if not isinstance(tool_name, str) or not tool_name.strip():
            errors.append(
                f"Step '{step_label}' has no valid tool name."
            )

     # Check if the plan only uses tools that actually exists/ are available to the agent
        elif tool_name not in tool_names:
            errors.append(
                f"Step '{step_label}' uses unknown tool "
                f"'{tool_name}'."
            )

        # Validate the description and justification.
        for field in ("description", "reason"):
            value = step.get(field)

            if not isinstance(value, str) or not value.strip():
                errors.append(
                    f"Step '{step_label}' has no valid '{field}'."
                )

        # Validate step dependencies.
        dependencies = step.get("depends_on", [])

        if not isinstance(dependencies, list):
            errors.append(
                f"Step '{step_label}' has invalid dependencies."
            )
            continue

        seen_dependencies = set()

        for dependency in dependencies:
            if not isinstance(dependency, str):
                errors.append(
                    f"Step '{step_label}' has a non-string dependency."
                )
                continue

            if dependency in seen_dependencies:
                errors.append(
                    f"Step '{step_label}' contains duplicate "
                    f"dependency '{dependency}'."
                )
                continue

            seen_dependencies.add(dependency)

            if dependency == step_id:
                errors.append(
                    f"Step '{step_label}' depends on itself."
                )
                continue

            if dependency not in step_positions:
                errors.append(
                    f"Step '{step_label}' references unknown "
                    f"dependency '{dependency}'."
                )
                continue

            if step_positions[dependency] >= index:
                errors.append(
                    f"Step '{step_label}' depends on "
                    f"'{dependency}', which does not precede it."
                )

        # Validate the execution condition's data type.
        condition = step.get("execution_condition")

        if condition is not None:
            if not isinstance(condition, str) or not condition.strip():
                errors.append(
                    f"Step '{step_label}' has an invalid "
                    "execution condition."
                )

    # Reject the plan if any validation failed.
    if errors:
        return reject(errors)

    # Approve the plan for the next processing stage.
    return {
        "plan_valid": True,
        "validation_errors": [],
        "status": "plan_valid",
        "history": [
            create_log("plan_valid", [])
        ]
    }
