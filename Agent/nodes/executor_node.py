
"""
Execute exactly one authorized ERPNext tool action.

The Executor receives an action selected by Governance.
It does not use an LLM, modify plans, evaluate execution
conditions or advance the current plan step.
"""

from copy import deepcopy
from datetime import datetime, timezone
from typing import Any, Mapping

from Agent.state import PlanningState


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _event(event: str, **details: Any) -> dict[str, Any]:
    """
    Create an event for the agent's decision history.
    """
    return {
        "event": event,
        **details,
        "timestamp": _now(),
    }


def _identity(action: dict[str, Any]) -> dict[str, Any]:
    """
    Extract the fields identifying an executable action.
    """
    return {
        "step_id": action.get("step_id"),
        "tool": action.get("tool"),
        "args": action.get("args"),
    }


def _is_authorized(
    state: PlanningState,
    action: dict[str, Any],
) -> bool:
    """
    Verify authorization for the exact prepared action.

    Automatic authorization requires a matching final_action.

    Human authorization supports approve, select and edit
    decisions generated by the Human Review node.
    """

    governance = state.get("governance") or {}
    status = state.get("status")

    if not isinstance(governance, dict):
        return False

    # Automatic Governance approval.
    if status == "auto":
        approved = governance.get("final_action")

        return (
            governance.get("decision") == "auto"
            and isinstance(approved, dict)
            and _identity(approved) == _identity(action)
        )

    # Explicit Human Review approval.
    if status == "approved":
        human_action = governance.get("human_action")

        if human_action == "approve":
            proposal = governance.get("proposal")

            return (
                isinstance(proposal, dict)
                and _identity(proposal) == _identity(action)
            )

        if human_action == "select":
            options = governance.get("options") or []

            return any(
                isinstance(option, dict)
                and option.get("executable") is True
                and isinstance(option.get("action"), dict)
                and _identity(option["action"]) == _identity(action)
                for option in options
            )

        if human_action == "edit":
            # Human Review explicitly accepted the edited action.
            # Additional argument and policy validation is required
            # before enabling write operations in production.
            return (
                isinstance(action.get("args"), dict)
                and isinstance(governance.get("proposal"), dict)
                and action.get("step_id")
                == governance["proposal"].get("step_id")
                and action.get("tool")
                == governance["proposal"].get("tool")
            )

    return False


def _normalize_result(
    raw_result: Any,
    specification: dict[str, Any],
) -> dict[str, Any]:
    """
    Validate and normalize the tool's business result.

    The current implementation supports simple result_fields
    specifications. Missing optional fields are not rejected.
    """

    if not isinstance(raw_result, dict):
        raise TypeError(
            "Tool output must be a dictionary."
        )

    if raw_result.get("success") is False:
        raise RuntimeError(
            str(
                raw_result.get("error")
                or "The tool reported an unsuccessful operation."
            )
        )

    if raw_result.get("error"):
        raise RuntimeError(str(raw_result["error"]))

    fields = specification.get("result_fields")

    if not isinstance(fields, dict):
        raise ValueError(
            "The tool specification must declare result_fields."
        )

    supported_types = {
        "str": str,
        "bool": bool,
        "int": int,
        "float": (int, float),
        "list": list,
        "dict": dict,
    }

    normalized = {}

    for field_name, declared_type in fields.items():

        if field_name not in raw_result:
            continue

        expected_type = supported_types.get(declared_type)

        if expected_type is None:
            raise ValueError(
                f"Unsupported result type: {declared_type}"
            )

        value = raw_result[field_name]

        if not isinstance(value, expected_type):
            raise TypeError(
                f"Invalid type for result field '{field_name}'."
            )

        # Python treats bool as a subclass of int.
        if (
            declared_type in ("int", "float")
            and isinstance(value, bool)
        ):
            raise TypeError(
                f"Invalid numeric value for field '{field_name}'."
            )

        normalized[field_name] = deepcopy(value)

    return normalized


def executor(
    state: PlanningState,
    *,
    registry: Mapping[str, Any],
) -> dict[str, Any]:
    """
    Execute one authorized tool call and record its outcome.

    The registry maps tool names to objects implementing invoke().

    The Evaluator handles business success, plan progress,
    failure recovery and selection of the next step.
    """

    plan = state.get("plan") or []
    current = state.get("current_step", 0)

    action = state.get("prepared_action") or {}
    step_results = deepcopy(
        state.get("step_results") or {}
    )

    def blocked(reason: str) -> dict[str, Any]:
        """
        Block execution before invoking a tool.
        """
        return {
            "status": "execution_blocked",
            "execution_error": reason,
            "history": [
                _event(
                    "execution_blocked",
                    reason=reason,
                )
            ],
        }

    # Verify that the plan has been validated.
    if state.get("plan_valid") is not True:
        return blocked(
            "The plan has not been validated."
        )

    # Verify the current step index.
    if (
        not isinstance(current, int)
        or isinstance(current, bool)
        or not 0 <= current < len(plan)
    ):
        return blocked(
            "Invalid current step index."
        )

    step = plan[current]
    step_id = step.get("id")
    tool_name = step.get("tool")

    # Only pending steps may be executed.
    if step.get("status", "pending") != "pending":
        return blocked(
            "The current step is not pending."
        )

    # Prevent executing an already recorded step.
    if step_id in step_results:
        return blocked(
            f"Step '{step_id}' already has an execution record."
        )

    # Check that the prepared action matches the plan.
    if (
        not isinstance(action, dict)
        or action.get("step_id") != step_id
        or action.get("tool") != tool_name
        or not isinstance(action.get("args"), dict)
    ):
        return blocked(
            "The prepared action does not match the current step."
        )

    # Require authorization from Governance or Human Review.
    if not _is_authorized(state, action):
        return blocked(
            "Governance has not authorized this exact action."
        )

    # Resolve the declared tool specification.
    specification = next(
        (
            item
            for item in state.get("available_tools", [])
            if (
                isinstance(item, dict)
                and item.get("name") == tool_name
            )
        ),
        None,
    )

    if specification is None:
        return blocked(
            f"Tool '{tool_name}' is not in the tool catalog."
        )

    # Resolve the actual executable tool.
    tool = registry.get(tool_name)

    if tool is None:
        return blocked(
            f"Tool '{tool_name}' is not registered."
        )

    if not callable(getattr(tool, "invoke", None)):
        return blocked(
            f"Tool '{tool_name}' does not support invoke()."
        )

    # Execute exactly one tool invocation.
    try:
        raw_result = tool.invoke(
            deepcopy(action["args"])
        )

        normalized_result = _normalize_result(
            raw_result,
            specification,
        )

        step_results[step_id] = {
            "status": "completed",
            "result": normalized_result,
            "reason": "Tool invocation succeeded.",
        }

        return {
            "step_results": step_results,
            "prepared_action": {},
            "candidates": [],
            "n_requested": 0,
            "execution_error": "",
            "status": "execution_succeeded",
            "history": [
                _event(
                    "tool_executed",
                    step_id=step_id,
                    tool=tool_name,
                    status="completed",
                )
            ],
        }

    except Exception as exc:
        error = f"{type(exc).__name__}: {exc}"

        step_results[step_id] = {
            "status": "failed",
            "result": None,
            "reason": error,
        }

        return {
            "step_results": step_results,
            "prepared_action": {},
            "candidates": [],
            "n_requested": 0,
            "execution_error": error,
            "status": "execution_failed",
            "history": [
                _event(
                    "tool_execution_failed",
                    step_id=step_id,
                    tool=tool_name,
                    error=error,
                )
            ],
        }
