"""
This file defines the output format of the planner node, using pydantic (for JSON)
"""

from pydantic import BaseModel, Field

"""
A plan step consits of an ID, the tool that is used during the step, a description of the step's goal and which steps it depends on (their ID)
Further, some steps may be conditional and for confidence and tracability, the LLM should give a reason for their decision of every step 
"""

class PlanStep(BaseModel):
    """
    Represent an individual step in a business process plan.
    """

    id: str = Field(
        description="Unique identifier of the execution step"
    )

    tool: str = Field(
        description="Exact name of the tool to execute"
    )

    description: str = Field(
        description="Business objective of the step"
    )

    depends_on: list[str] = Field(
        default_factory=list,
        description="IDs of required predecessor steps"
    )

    execution_condition: str | None = Field(
        default=None,
        description=(
            "Optional condition determining whether the step "
            "should execute. The condition must reference "
            "the result of a previous step. "
            "A downstream component must evaluate this "
            "condition before execution."
        )
    )

    reason: str = Field(
        description=(
            "Brief justification explaining why this step "
            "is necessary to achieve the business goal"
        )
    )


"""
A plan consists of the overall goal and the stepsthat need to be taken to achieve that goal
It also saves which information is missing for successful completion (needs to be provided by humann or assumed by the LLM) and the reason, why it was aborted (if so)
"""

class Plan(BaseModel):
    """
    Represent a complete business process plan generated by the LLM.
    """

    goal: str = Field(
        description="Intended final business state"
    )

    steps: list[PlanStep] = Field(
        default_factory=list,
        description="Ordered list of proposed execution steps"
    )

    missing_info: list[str] = Field(
        default_factory=list,
        description=(
            "Information required to complete the business "
            "instruction that cannot be obtained using "
            "the available tools"
        )
    )

    abort_reason: str = Field(
        default="",
        description=(
            "Reason why the requested business goal cannot "
            "be achieved with the available capabilities"
        )
    )

